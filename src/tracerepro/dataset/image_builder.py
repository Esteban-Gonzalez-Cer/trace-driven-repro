"""Build one pinned Docker image per bug manifest: `bug_env:{id}` (plan §5.1).

Steps: snapshot the parent commit `c_bug` without `.git`, write a Dockerfile with the manifest's
exact Python version and pinned dependency lock, build with network on, then record the
installed package versions (`pip freeze`) from an offline container. The freeze is what makes
"a rebuild produces the same installed package versions" checkable.

Usage:
    python -m tracerepro.dataset.image_builder [--no-cache] [MANIFEST ...]
With no manifests, builds every `benchmark/manifests/*.yaml`.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import shutil
import sys
from collections.abc import Iterable
from dataclasses import asdict, dataclass
from pathlib import Path

import docker
import docker.errors

from tracerepro.dataset.lockfile import Pin, load_lock, normalize_name
from tracerepro.dataset.manifest import PROJECT_ROOT, Manifest, load_manifest
from tracerepro.dataset.repo import clone_name, ensure_clone, materialize

RUNNER_UID = 1000
# Present in the python:*-slim base image rather than installed from the lock.
BASE_PACKAGES = frozenset({"pip", "setuptools", "wheel"})
DEFAULT_WORK_DIR = PROJECT_ROOT / "work"
LOCK_NAME = "requirements.lock.txt"


class BuildFailed(RuntimeError):
    """The image could not be built or does not match its lock."""


@dataclass(frozen=True)
class BuildRecord:
    bug_id: str
    image_tag: str
    image_id: str
    base_image: str
    base_image_id: str
    c_bug: str
    dockerfile_sha256: str
    lock_sha256: str | None
    freeze: list[str]
    built_at: str


def render_dockerfile(manifest: Manifest) -> str:
    """Deterministic Dockerfile for a manifest. All interpolated values are validated fields."""
    lines = [
        "# Generated by tracerepro.dataset.image_builder. Do not edit.",
        f"FROM {manifest.base_image}",
        f'LABEL org.tracerepro.bug_id="{manifest.id}" '
        f'org.tracerepro.repo="{manifest.repo}" '
        f'org.tracerepro.c_bug="{manifest.c_bug}"',
        "ENV PYTHONDONTWRITEBYTECODE=1 PIP_NO_CACHE_DIR=1 PIP_DISABLE_PIP_VERSION_CHECK=1",
        f"RUN useradd --create-home --uid {RUNNER_UID} runner",
    ]
    if manifest.deps_lock is not None:
        lines += [
            f"COPY {LOCK_NAME} /opt/tracerepro/{LOCK_NAME}",
            f"RUN pip install --no-deps -r /opt/tracerepro/{LOCK_NAME}",
        ]
    lines += [
        "COPY repo/ /repo/",
        "WORKDIR /repo",
        # --no-deps: everything comes from the lock; pip check proves the lock is complete.
        "RUN pip install --no-deps -e /repo && pip check",
        f"USER {RUNNER_UID}",
    ]
    return "\n".join(lines) + "\n"


def prepare_context(manifest: Manifest, work_dir: Path) -> Path:
    """Assemble the Docker build context under `work_dir/builds/{id}/context`."""
    lock_path = manifest.deps_lock_path()
    if lock_path is not None:
        load_lock(lock_path)  # validate before anything is built

    git_dir = ensure_clone(
        manifest.repo_location(),
        work_dir / "repos",
        clone_name(manifest.repo),
        [manifest.c_bug, manifest.c_fix],
    )
    context = work_dir / "builds" / manifest.id / "context"
    if context.exists():
        shutil.rmtree(context)
    context.mkdir(parents=True)
    materialize(git_dir, manifest.c_bug, context / "repo")
    if lock_path is not None:
        shutil.copyfile(lock_path, context / LOCK_NAME)
    (context / "Dockerfile").write_text(render_dockerfile(manifest))
    return context


def check_freeze(freeze: list[str], pins: list[Pin]) -> None:
    """Every installed package must come from the lock (exact version) or the base image."""
    locked = {p.key: p.version for p in pins}
    problems = []
    for line in freeze:
        name, _, version = line.partition("==")
        key = normalize_name(name)
        if key in BASE_PACKAGES:
            continue
        if key not in locked:
            problems.append(f"{line} is installed but not in the lock")
        elif locked[key] != version:
            problems.append(f"{line} is installed but the lock pins {locked[key]}")
    unconditional = {p.key for p in pins if p.marker is None}
    installed = {normalize_name(line.partition("==")[0]) for line in freeze}
    problems += [f"{k} is pinned but not installed" for k in sorted(unconditional - installed)]
    if problems:
        raise BuildFailed("; ".join(problems))


def _log_text(chunks: Iterable[object]) -> str:
    parts = []
    for chunk in chunks:
        if isinstance(chunk, dict):
            parts.append(str(chunk.get("stream") or chunk.get("error") or ""))
    return "".join(parts)


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build_image(
    manifest: Manifest,
    *,
    work_dir: Path = DEFAULT_WORK_DIR,
    no_cache: bool = False,
    client: docker.DockerClient | None = None,
) -> BuildRecord:
    client = client or docker.from_env()
    context = prepare_context(manifest, work_dir)
    out_dir = context.parent
    try:
        image, logs = client.images.build(
            path=str(context), tag=manifest.image_tag, rm=True, forcerm=True, nocache=no_cache
        )
    except docker.errors.BuildError as exc:
        (out_dir / "build.log").write_text(_log_text(exc.build_log))
        raise BuildFailed(f"{manifest.id}: docker build failed: {exc.msg}") from exc
    (out_dir / "build.log").write_text(_log_text(logs))

    output = client.containers.run(
        manifest.image_tag,
        ["python", "-m", "pip", "freeze", "--all", "--exclude-editable"],
        network_disabled=True,
        remove=True,
        stdout=True,
        stderr=False,
    )
    freeze = sorted(line for line in output.decode().splitlines() if line and "==" in line)
    lock_path = manifest.deps_lock_path()
    check_freeze(freeze, load_lock(lock_path) if lock_path else [])

    record = BuildRecord(
        bug_id=manifest.id,
        image_tag=manifest.image_tag,
        image_id=str(image.id),
        base_image=manifest.base_image,
        base_image_id=str(client.images.get(manifest.base_image).id),
        c_bug=manifest.c_bug,
        dockerfile_sha256=_sha256(context / "Dockerfile"),
        lock_sha256=_sha256(lock_path) if lock_path else None,
        freeze=freeze,
        built_at=dt.datetime.now(dt.UTC).isoformat(timespec="seconds"),
    )
    (out_dir / "build.json").write_text(json.dumps(asdict(record), indent=2) + "\n")
    return record


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("manifests", nargs="*", type=Path)
    parser.add_argument("--no-cache", action="store_true", help="rebuild every layer")
    parser.add_argument("--work-dir", type=Path, default=DEFAULT_WORK_DIR)
    args = parser.parse_args(argv)

    paths = args.manifests or sorted((PROJECT_ROOT / "benchmark" / "manifests").glob("*.yaml"))
    if not paths:
        print("no manifests to build", file=sys.stderr)
        return 1
    failures = 0
    for path in paths:
        try:
            manifest = load_manifest(path)
            record = build_image(manifest, work_dir=args.work_dir, no_cache=args.no_cache)
        except Exception as exc:
            failures += 1
            print(f"FAIL {path}: {exc}", file=sys.stderr)
            continue
        print(f"ok   {record.image_tag}  {record.image_id[:19]}  {len(record.freeze)} packages")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
